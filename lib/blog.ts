export const postBySlug = (slug: string) => posts.find((post) => post.slug === slug);

/** Posts of one kind first, then the rest; used for "related" lists. */
export const relatedPosts = (kind: BlogKind, except?: string, limit = 3) =>
  [...posts.filter((post) => post.kind === kind), ...posts.filter((post) => post.kind !== kind)].filter((post) => post.slug !== except).slice(0, limit);
